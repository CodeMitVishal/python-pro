"""Module 25 · A guided tour of the Django bookstore project

  pip install django djangorestframework

Django is "batteries included": ORM + migrations, an admin back office, templates,
forms, auth, security middleware and a test runner, all in one framework.
Django REST Framework (DRF) adds serializers and viewsets for JSON APIs.

  bookstore_project/
  ├── manage.py                 # the command-line tool: runserver, migrate, test, shell...
  ├── config/settings.py        # one settings file (secrets from env vars!)
  ├── config/urls.py            # top-level routes
  └── catalog/                  # an "app": one feature area
      ├── models.py             # Author, Book            -> tables
      ├── migrations/           # generated by makemigrations
      ├── admin.py              # back-office screens
      ├── views.py + templates/ # HTML pages
      ├── serializers.py + api.py + urls.py   # the JSON API
      └── tests.py

This script runs the project against a temporary database and visits the pages.
For the real thing:
    cd 25_django/bookstore_project
    python manage.py migrate
    python manage.py createsuperuser
    python manage.py runserver        -> http://127.0.0.1:8000/  /api/  /admin/

TEACHING NOTES
  Why it matters  Many Python web jobs are Django jobs: ORM, admin, auth and migrations out of
                  the box.
  Picture it      Django is a fully equipped kitchen: you cook the business logic, the
                  appliances are already there.
  Watch out       QuerySets are lazy and N+1 is easy to create: use select_related /
                  prefetch_related.
  In real jobs    Admin panels for staff, DRF APIs for apps, migrations in every deploy.
  Interview       Q: select_related vs prefetch_related?
                  A: select_related: FK/one-to-one with a JOIN. prefetch_related: reverse FK/M2M
                     with a second IN query.

Run it:  python 25_django/01_django_tour.py
"""
import os
import sys
import tempfile
from decimal import Decimal
from pathlib import Path

project = Path(__file__).parent / "bookstore_project"
sys.path.insert(0, str(project))
os.environ["DJANGO_SETTINGS_MODULE"] = "config.settings"
os.environ["DJANGO_DB"] = str(Path(tempfile.mkdtemp()) / "tour.sqlite3")

import django  # noqa: E402

django.setup()

import logging  # noqa: E402

logging.getLogger("django.request").setLevel(logging.ERROR)   # hide expected 404/403 warnings

from django.contrib.auth.models import User  # noqa: E402
from django.core.management import call_command  # noqa: E402
from django.db import connection  # noqa: E402
from django.test import Client  # noqa: E402
from django.test.utils import CaptureQueriesContext  # noqa: E402

from catalog.models import Author, Book  # noqa: E402

call_command("migrate", verbosity=0)                  # create every table from the migrations
print("tables:", [t for t in connection.introspection.table_names() if t.startswith("catalog")])

# --- The ORM: Django's query API --------------------------------------------------------------
martin = Author.objects.create(name="Robert C. Martin", country="US")
ramalho = Author.objects.create(name="Luciano Ramalho", country="BR")
Book.objects.bulk_create([
    Book(title="Clean Code", author=martin, price=Decimal("34.50")),
    Book(title="Clean Architecture", author=martin, price=Decimal("29.90"), in_stock=False),
    Book(title="Fluent Python", author=ramalho, price=Decimal("49.90")),
])
print("cheaper than 35:", list(Book.objects.filter(price__lt=35).values_list("title", flat=True)))
print("by Martin:      ", Book.objects.filter(author__name__startswith="Robert").count())

with CaptureQueriesContext(connection) as ctx:
    titles = [f"{b.title}/{b.author.name}" for b in Book.objects.select_related("author")]
print("select_related: ", len(ctx.captured_queries), "query for", len(titles), "books + authors")

# --- Pages and API through the test client ------------------------------------------------------
client = Client()
html = client.get("/?q=clean").content.decode()
print("\nGET /?q=clean   ->", html.count("<li>"), "books in the HTML")
print("GET /books/99/  ->", client.get("/books/99/").status_code)
api = client.get("/api/books/?in_stock=true").json()
print("GET /api/books/ ->", api["count"], "in stock:", [b["title"] for b in api["results"]])
print("GET /api/authors/ ->", [(a["name"], a["book_count"]) for a in client.get("/api/authors/").json()["results"]])
print("POST as guest   ->", client.post("/api/books/", {"title": "X", "author": 1, "price": "5"}).status_code)

client.force_login(User.objects.create_user("vishal", password="pw"))
r = client.post("/api/books/", {"title": "Python Pro", "author": ramalho.id, "price": "19.99"})
print("POST logged in  ->", r.status_code, r.json()["title"])
admin_page = client.get("/admin/")
print("GET /admin/     ->", admin_page.status_code, "(redirects to login: staff only)")
